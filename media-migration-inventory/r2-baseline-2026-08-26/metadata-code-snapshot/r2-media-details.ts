export function r2AssetIdFromUrl(url?: string): string | undefined {
  const match = url?.match(/\/media\/([0-9a-f-]{16,})\/?$/i);
  return match?.[1];
}

export function getR2MediaDetails(url?: string): R2MediaDetail | undefined {
  const assetId = r2AssetIdFromUrl(url);
  return assetId ? R2_MEDIA_DETAILS_BY_ASSET_ID[assetId] : undefined;
}

export function r2ImageDimensions(url?: string, fallback = { width: 1200, height: 675 }) {
  const detail = getR2MediaDetails(url);
  return { width: detail?.width || fallback.width, height: detail?.height || fallback.height };
}
